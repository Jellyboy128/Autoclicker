package com.example.autoclicker

import android.app.Activity
import android.app.AlertDialog

object Help {
    private const val TEXT = """БЫСТРЫЙ СТАРТ
1. Нажмите «Открыть специальные возможности» и включите службу Autoclicker.
2. Напишите скрипт, введите имя и нажмите «Сохранить».
3. Нажмите «Старт» на плавающей панели. Панель можно перетаскивать за значок ☰.
Кнопка «Стоп» на панели останавливает скрипт в любой момент. Кнопка ✕ закрывает панель, вернуть её можно кнопкой «Показать панель» в приложении.
Переключатель «Зациклить весь скрипт» заставляет скрипт бесконечно повторяться с начала.

КОМАНДЫ
click(x, y) или tap(x, y): нажатие в точку.
sleep(мс) или wait(мс): пауза в миллисекундах (1000 = 1 секунда).
swipe(x1, y1, x2, y2, мс): свайп из первой точки во вторую за указанное время. Чем больше мс, тем медленнее.
log("текст"): записать строку в журнал.
stop(): остановить скрипт.
break(): выйти из текущего цикла. Вне цикла останавливает скрипт.

ЦИКЛЫ
repeat(5) { ... }: повторить 5 раз.
repeat(forever) { ... }: повторять бесконечно, пока не сработает break(), stop() или кнопка «Стоп».

УСЛОВИЯ
if (условие) { ... } else { ... }
else if (условие) { ... } тоже работает.
pixel(x, y) == "#RRGGBB": цвет пикселя равен указанному. Для «не равен» используйте !=.
findColor("#RRGGBB", x1, y1, x2, y2): ищет цвет в прямоугольнике от (x1, y1) до (x2, y2). Если нашёл, условие верно, а найденное место доступно как found (или foundX и foundY).
findColor("#RRGGBB", x1, y1, x2, y2, 30): шестое число задаёт допуск цвета (по умолчанию 10).
findColor("#111111", "#999999", x1, y1, x2, y2): несколько цветов за один скриншот. Цвета проверяются по порядку списка, и найденный первым даёт found. Какой именно цвет сработал, покажет foundColor, например if (foundColor == "#999999") { ... }.
Можно комбинировать: ! (не), && (и), || (или), а также true и false.

ТОЧКИ
point(кнопка, 540, 1200): даёт имя точке. Дальше вместо пары координат пишите имя: click(кнопка), pixel(кнопка), swipe(а, б, 300), findColor("#00FF00", лево, право).
После findColor можно сделать click(found).

СКОРОСТЬ СКРИНШОТОВ
fps(1), fps(2) или fps(3): сколько скриншотов в секунду делать для pixel и findColor. Команда должна стоять в самом начале скрипта (перед ней можно только point). Без неё работает максимум: 3 в секунду.

ПИПЕТКА
Кнопка «Пипетка» на панели включает режим выбора. Тапайте по нужным точкам: каждый тап показывает координаты и цвет и копирует готовые строки point(...). Нажмите «Готово», затем вставьте строки в скрипт (долгое нажатие → Вставить). Строки также попадают в журнал.

ПРОЧЕЕ
Комментарии: всё после // в строке игнорируется.
Команды можно писать без точки с запятой, но с ней тоже работает.
Ошибки показываются с номером строки в журнале приложения и во всплывающем сообщении.
Размер экрана: сохраните и запустите скрипт log(pixel(99999, 99999)); в журнале появится размер.

ОГРАНИЧЕНИЯ
Скриншоты ограничены Android примерно тремя в секунду.
В приложениях с защитой экрана (банки и некоторые игры) скриншот чёрный, и pixel с findColor не работают.
Банковские и некоторые другие приложения могут блокировать автоматические нажатия."""

    fun show(activity: Activity) {
        AlertDialog.Builder(activity)
            .setTitle("Справка")
            .setMessage(TEXT)
            .setPositiveButton("Закрыть", null)
            .show()
    }
}
